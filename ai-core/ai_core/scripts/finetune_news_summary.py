CONTEXT = 512  # Model stays 1024; fixed visible prefix/output budget limits this experiment's GPU time.
OUTPUT_TOKENS = 96
CER = 0.1347


def title_source(row):
    return (row["summary"] + " " + row["body"]).strip()


def aligned_source(row, noisy):
    return row["source_asr" if noisy else "body"].strip()  # Production strips transcript edges before tokenizing.


@torch.inference_mode()
def evaluate(model, rows, tok, device, noisy=False, fmt="title", aligned=False):
    model.eval()
    eos = tok.special_tokens["<eos>"]
    values = []
    for i, row in enumerate(rows):
        source = row["body"] if aligned or fmt == "sum" else title_source(row)
        if aligned:
            source = aligned_source(row, noisy)
        elif noisy:
            source = normalize_to_asr(source, cer=CER, seed=i)
        ids = summary_prompt_ids(source, tok, fmt, CONTEXT, OUTPUT_TOKENS)
        prompt = torch.tensor([ids], device=device)
        with torch.autocast("cuda", dtype=torch.float16, enabled=device.type == "cuda"):
            output = model.generate(prompt, OUTPUT_TOKENS, temperature=0, eos_id=eos)
        generated = output[0, len(ids):].tolist()
        pred = tok.decode(generated).strip()
        # Both systems see exactly the same truncated source (without control marker/EOS).
        visible = tok.decode(ids[:-1]).removeprefix(CONTROL_TOKENS[fmt]+" ")
        lead = re.split(r"(?<=[.!?])\s+", visible, maxsplit=1)[0].strip()
        reference = row["summary"] if fmt == "sum" else row["title"]
        words = pred.casefold().split()
        trigrams = list(zip(words, words[1:], words[2:]))
        values.append({"id": row["id"], "reference": reference, "prediction": pred,
                       "lead1": lead, "rouge_l": rouge_l(reference, pred),
                       "lead1_rouge_l": rouge_l(reference, lead),
                       "eos_stop": bool(generated and generated[-1] == eos),
                       "cap_hit": len(generated) == OUTPUT_TOKENS and generated[-1] != eos,
                       "repeated_trigram_fraction": 1-len(set(trigrams))/len(trigrams) if trigrams else 0.})
    return values


def mean(values, key):
    return float(np.mean([v[key] for v in values]))


def encoded_dataset(rows, tok, noisy, aligned=False):
    title = [(aligned_source(r, noisy) if aligned else title_source(r), r["title"]) for r in rows]
    summary = [(aligned_source(r, noisy) if aligned else r["body"], r["summary"])
               for r in rows if len(r["summary"].split()) >= 5]
    # Natural editorial sapo labels, never generated by another model; summary input excludes sapo.
    result = []
    for fmt, pairs in (("title", title), ("sum", summary), ("cap", title)):
        ds = SummaryPairDataset(pairs, tok, fmt=fmt, context_len=CONTEXT,
                                max_target_tokens=OUTPUT_TOKENS, asr_noise=noisy and not aligned, asr_cer=CER)
        items = [ds[i] for i in range(len(ds))]
        result.extend(items)
        if fmt == "title":
            result.extend(items)  # 2:1:1 title/summary/caption, fixed before evaluation.
        print(f"encoded {fmt}: {len(items)} | ASR noise={noisy}", flush=True)
    assert result and all(bool(y.ne(-100).any()) for _, y in result)
    return result


def aligned_validation(model, rows, tok, device):
    """Select by paired summary ROUGE-L; auxiliary formats cannot change the score."""
    outputs = {name: evaluate(model, rows, tok, device, noisy=noisy, fmt=fmt, aligned=True)
               for name, fmt, noisy in (("sum_clean", "sum", False), ("sum_asr", "sum", True),
                                        ("title_clean", "title", False), ("cap_clean", "cap", False))}
    metrics = {name: {key: mean(values, key) for key in
                     ("rouge_l", "lead1_rouge_l", "eos_stop", "cap_hit", "repeated_trigram_fraction")}
               for name, values in outputs.items()}
    score = (metrics["sum_clean"]["rouge_l"]+metrics["sum_asr"]["rouge_l"])/2
    return score, metrics, outputs


class ReplayBatchSampler:
    """Every microbatch contains equal clean/noisy examples, shuffled independently."""

    def __init__(self, n_items, batch_size, seed):
        if n_items < 1 or batch_size < 2 or batch_size % 2:
            raise ValueError("mixed replay needs nonempty equal pools and an even batch size")
        self.n_items, self.half = n_items, batch_size // 2
        self.generator = torch.Generator().manual_seed(seed)

    def __iter__(self):
        clean = torch.randperm(self.n_items, generator=self.generator).tolist()
        noisy = torch.randperm(self.n_items, generator=self.generator).tolist()
        for start in range(0, self.n_items, self.half):
            yield clean[start:start+self.half] + [self.n_items+i for i in noisy[start:start+self.half]]

    def __len__(self):
        return math.ceil(self.n_items/self.half)


def replay_regressions(metrics, baseline):
    """A paired mean must not hide deterioration on either input condition."""
    failed = []
    for name in ("sum_clean", "sum_asr"):
        for key in ("rouge_l", "eos_stop", "cap_hit", "repeated_trigram_fraction"):
            value, reference = metrics[name][key], baseline[name][key]
            if not math.isfinite(reference) or not 0 <= reference <= 1:
                raise ValueError("invalid replay baseline")
            delta = value-reference if key in ("rouge_l", "eos_stop") else reference-value
            if not math.isfinite(value) or not 0 <= value <= 1 or delta < -1e-12:
                failed.append(f"{name}.{key}")
    return failed


def select_candidate(candidates, guarded=False):
    # Rejected rounds use -1 only for Trainer bookkeeping; never export them for serving.
    eligible = [c for c in candidates if not guarded or c["metric"] >= 0]
    return max(eligible, key=lambda c: c["metric"], default=None)


def validate_aligned_bundle(data, manifest, train, val):
    if len(val) < VAL_COUNT or [r["id"] for r in val[:VAL_COUNT]] != manifest["validation_ids"]:
        raise ValueError("need64 fixed validation pairs; do not relax screening to start training")
    if manifest["context"] != CONTEXT or manifest["output_tokens"] != OUTPUT_TOKENS or manifest["asr_cer"] != CER:
        raise ValueError("prepared profile differs from this recipe")
    bad = [r["id"] for r in train+val if not has_sentence_ending(r["summary"])]
    if bad:
        raise ValueError(f"{len(bad)} summaries have invalid sentence endings; prepare a new dataset version")
    check_human_audit(data/"human_audit.csv", manifest, {"train":train, "val":val})


def training_schedule(n_articles, batch_size, grad_accum, aligned, mixed_replay=False):
    if mixed_replay and not aligned:
        raise ValueError("mixed replay requires the confirmed aligned dataset")
    if not aligned:
        return (("clean",16000,False),("asr",4000,True)), 1000
    # A small screened set must not inherit the old76k-article update budget.
    epoch_steps = math.ceil(4*n_articles/(batch_size*max(1,grad_accum)))
    if epoch_steps < 1:
        raise ValueError("empty training set")
    stages = (("mixed",5*epoch_steps,None),) if mixed_replay else (("clean",4*epoch_steps,False),("asr",epoch_steps,True))
    return stages, epoch_steps


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--data", required=True)
    p.add_argument("--pretrain", required=True)
    p.add_argument("--vocab", required=True)
    p.add_argument("--output", required=True)
    p.add_argument("--mixed-replay", action="store_true")
    p.add_argument("--baseline", help="Same-GPU initialization evaluation, required for mixed replay")
    args = p.parse_args()
    torch.set_num_threads(4)
    data, out = Path(args.data), Path(args.output)
    manifest = json.loads((data / "news_manifest.json").read_text(encoding="utf-8"))
    aligned = manifest.get("protocol") == PROTOCOL
    if manifest.get("protocol") and not aligned:
        raise ValueError("unknown prepared-data protocol")
    for name, info in manifest["splits"].items():
        assert file_checksum(str(data / f"news_{name}.json")) == info["sha1"], f"{name} checksum changed"
    train = json.loads((data / "news_train.json").read_text(encoding="utf-8"))
    val = json.loads((data / "news_val.json").read_text(encoding="utf-8"))
    if aligned:
        validate_aligned_bundle(data, manifest, train, val)
    baseline = None
    if args.mixed_replay:
        if not aligned or not args.baseline:
            raise ValueError("mixed replay requires confirmed aligned data and a same-GPU baseline")
        baseline = json.loads(Path(args.baseline).read_text(encoding="utf-8"))
        if (baseline["init_sha256"] != hashlib.sha256(Path(args.pretrain).read_bytes()).hexdigest()
                or baseline["data_manifest_sha256"] != hashlib.sha256((data/"news_manifest.json").read_bytes()).hexdigest()
                or baseline["n_val"] != VAL_COUNT or baseline["eval_precision"] != "fp16_autocast"):
            raise ValueError("replay baseline does not match initialization/data/evaluation profile")
        replay_regressions(baseline["metrics"], baseline["metrics"])
    val = val[:VAL_COUNT if aligned else 128]
    tok = BPETokenizer.load(args.vocab)
    if aligned and file_checksum(args.vocab) != manifest["vocab_sha1"]:
        raise ValueError("prepared tokenizer checksum changed")
    if not torch.cuda.is_available():
        raise SystemExit("GPU required for the real training run")
    out.mkdir(parents=True, exist_ok=False if aligned else True)
    for row in train[:1000]:
        assert tok.decode(tok.encode(row["title"])) == row["title"]
    ckpt = load_checkpoint(args.pretrain)
    cfg_path = Path(__file__).parents[1] / "training/configs/minigpt_finetune_summary.yaml"
    model_cfg, cfg = load_configs(str(cfg_path))
    assert all(ckpt["config"][k] == getattr(model_cfg, k)
               for k in ("d_model", "n_layers", "n_heads", "vocab_size", "context_len"))
    assert tok.vocab_size == model_cfg.vocab_size
    model = build_model("minigpt", ModelConfig(**ckpt["config"]))
    model.load_state_dict(ckpt["state_dict"])
    cfg.precision = "bf16" if torch.cuda.is_bf16_supported(including_emulation=False) else "fp16"
    stages, cfg.eval_every = training_schedule(len(train), cfg.batch_size, cfg.grad_accum, aligned, args.mixed_replay)
    vocab = json.loads(Path(args.vocab).read_text(encoding="utf-8"))
    metadata = {"corpus": manifest, "pretrain_sha1": file_checksum(args.pretrain),
                "prompt": "<format> source <eos>", "summary_context_len": CONTEXT,
                "max_target_tokens": OUTPUT_TOKENS, "asr_cer": CER,
                "selection": manifest["selection"] if aligned else "Mean of clean and ASR-noisy validation title ROUGE-L; no test tuning",
                "stages": stages, "eval_every": cfg.eval_every,
                "recipe": "mixed-replay-1to1-v1" if args.mixed_replay else "staged",
                "selection_guard": {"baseline_metrics":baseline["metrics"],
                                    "policy":"Both sum conditions: ROUGE/EOS >= init; repetition/cap <= init; tolerance1e-12",
                                    "baseline_sha256":hashlib.sha256(Path(args.baseline).read_bytes()).hexdigest()} if baseline else None}
    print("GPU", torch.cuda.get_device_name(0), "precision", cfg.precision,
          "params", sum(p.numel() for p in model.parameters()), flush=True)
    started = time.time()
    candidates = []
    for stage, steps, noisy in stages:
        if candidates:
            model.load_state_dict(load_checkpoint(str(candidates[-1]["path"]))["state_dict"])
        cfg.max_steps = steps
        cfg.ckpt_dir = str(out / stage)
        cfg.log_dir = str(out / "runs" / stage)
        dump_configs(model_cfg, cfg, str(out / f"{stage}_config.yaml"))
        if args.mixed_replay:
            clean = encoded_dataset(train, tok, False, aligned=True)
            noisy_items = encoded_dataset(train, tok, True, aligned=True)
            assert len(clean) == len(noisy_items)
            ds = clean + noisy_items
            loader = DataLoader(ds, batch_sampler=ReplayBatchSampler(len(clean),cfg.batch_size,cfg.seed), collate_fn=_pad_lm)
        else:
            ds = encoded_dataset(train, tok, noisy, aligned=aligned)
            loader = DataLoader(ds, batch_size=cfg.batch_size, shuffle=True, collate_fn=_pad_lm)
        validation_step = 0

        def metric(current, _loader, device):
            nonlocal validation_step
            validation_step += cfg.eval_every
            if aligned:
                score, values, predictions = aligned_validation(current, val, tok, device)
                regressions = replay_regressions(values,baseline["metrics"]) if baseline else []
                details = {"stage": stage, "step":validation_step, "selection_score": score, "formats": values,
                           "eligible":not regressions, "regressions":regressions,
                           "human_factuality": "NOT AUTOMATICALLY SCORED"}
                with (out / "validation_predictions.jsonl").open("a", encoding="utf-8") as f:
                    f.write(json.dumps({"stage":stage, "predictions":predictions}, ensure_ascii=False)+"\n")
                with (out / "validation.jsonl").open("a", encoding="utf-8") as f:
                    f.write(json.dumps(details)+"\n")
                print("validation", json.dumps(details), flush=True)
                return score if not regressions else -1.
            clean = evaluate(current, val[:64], tok, device)
            noise = evaluate(current, val[64:], tok, device, noisy=True)
            details = {"stage": stage, "clean_rouge_l": mean(clean, "rouge_l"),
                       "asr_rouge_l": mean(noise, "rouge_l"),
                       "lead1_clean": mean(clean, "lead1_rouge_l")}
            with (out / "validation.jsonl").open("a", encoding="utf-8") as f:
                f.write(json.dumps(details) + "\n")
            print("validation", json.dumps(details), flush=True)
            return (details["clean_rouge_l"] + details["asr_rouge_l"]) / 2

        trainer = Trainer(model, loader, val, cfg, minigpt_loss, model_cfg=model_cfg,
                          compute_metric=metric, bpe_vocab=vocab,
                          metadata={**metadata, "stage": stage})
        print("stage", stage, "steps", steps, flush=True)
        metrics = trainer.train()
        best_path = out / stage / "minigpt/best.pt"
        best = load_checkpoint(str(best_path))
        candidates.append({"stage": stage, "path": best_path, "metric": best["metrics"]["rouge_l"],
                           "train": metrics, "best_step": best["metrics"]["step"]})
        del trainer, loader, ds
    chosen = select_candidate(candidates, guarded=args.mixed_replay)
    final = out / "minigpt"
    if chosen:
        model.load_state_dict(load_checkpoint(str(chosen["path"]))["state_dict"])
        final.mkdir(exist_ok=True)
        shutil.copy2(chosen["path"], final / "best.pt")
        shutil.copy2(args.vocab, final / "bpe_vocab.json")
    if aligned:
        report = {"protocol": PROTOCOL, "status": "CANDIDATE_ONLY_HELDOUT_AND_HUMAN_EVALUATION_PENDING" if chosen else "NO_CANDIDATE_PASSED_NON_REGRESSION_GUARD",
                  "recipe":metadata["recipe"], "selection_guard":metadata["selection_guard"],
                  "seed": cfg.seed, "selected_stage": chosen["stage"] if chosen else None,
                  "selected_step": chosen["best_step"] if chosen else None,
                  "validation_metric": chosen["metric"] if chosen else None, "dataset": manifest,
                  "checkpoint_sha1": file_checksum(str(final / "best.pt")) if chosen else None,
                  "elapsed_hours": (time.time()-started)/3600,
                  "stages": [{k:v for k,v in c.items() if k!="path"} for c in candidates]}
        (out / "training_result.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
        print("CANDIDATE", json.dumps(report, ensure_ascii=False), flush=True)
        return  # A new experiment must not silently reopen the repeatedly inspected frozen test.
    # Test is opened only after all training and validation-based selection have finished.
    test = json.loads((data / "news_test.json").read_text(encoding="utf-8"))
    predictions = evaluate(model, test, tok, torch.device("cuda"))
    delta = np.array([r["rouge_l"] - r["lead1_rouge_l"] for r in predictions])
    rng = np.random.default_rng(1337)
    ci = np.quantile([rng.choice(delta, len(delta), replace=True).mean() for _ in range(2000)], [.025, .975])
    report = {"seed": cfg.seed, "n_test": len(test), "selected_stage": chosen["stage"],
              "selected_step": chosen["best_step"], "validation_metric": chosen["metric"],
              "rouge_l": mean(predictions, "rouge_l"), "lead1_rouge_l": mean(predictions, "lead1_rouge_l"),
              "delta": float(delta.mean()), "delta_ci95": ci.tolist(), "automatic_threshold_pass": bool(delta.mean() > 0),
              "human_evaluation": "PENDING: 30 real ASR transcripts, 3 raters, mean >=3/5",
              "elapsed_hours": (time.time() - started) / 3600,
              "checkpoint_sha1": file_checksum(str(final / "best.pt")), "dataset": manifest,
              "stages": [{k: v for k, v in c.items() if k != "path"} for c in candidates]}
    (out / "news_eval.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    (out / "test_predictions.jsonl").write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in predictions), encoding="utf-8")
    print("FINAL", json.dumps(report, ensure_ascii=False), flush=True)


if __name__ == "__main__":
    main()
